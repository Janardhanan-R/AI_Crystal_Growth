"""
04_generate_synthetic_data.py
==============================
Generates synthetic (T1..T5, Lc, Le, P, D) rows using the GP-based method
selected and justified in 02_METHODOLOGY_SELECTION.md.

LEAKAGE BOUNDARY: this script reads ONLY synthetic/data/original_train.csv.
It never reads original_val.csv or original_test.csv. The generator (a
GaussianProcessRegressor, same kernel family as this project's own
already-validated FastSurrogate/src/models.py::gpr_kernel) is fit
exclusively on the 67 original-train rows.

Generation procedure
---------------------
1. Inputs (T1..T5): sampled uniformly within the RANGES OBSERVED IN
   original_train.csv (continuous, not restricted to the original discrete
   DOE levels -- generating only the 96 original level-combinations would
   not be "new" data), then rejected/resampled until T1>=T2>=T3>=T4>=T5
   holds (the physical ordering constraint verified in 01_*, honored by
   100% of the original data).
2. Outputs Lc, Le: predicted by a GPR fit on original_train (T1..T5 ->
   Lc/Le), with noise added FROM THE GP's OWN PREDICTIVE STD at each
   sampled point (not an arbitrary noise scale) -- this is what "realistic
   measurement/simulation noise" means operationally here: noise
   proportional to the generator's own stated uncertainty.
3. Outputs D, P: computed ALGEBRAICALLY from generated Lc/Le, exactly as in
   the original data (D = Lc - Le, P = (Lc + Le)/2) -- NOT generated by a
   separate model. An earlier version of this script fit an independent GPR
   for D directly; that was rejected during development because it broke
   the exact D=Lc-Le identity that holds in every one of the 96 original
   rows (to float precision) by amounts comparable to D's own full range --
   i.e. it silently introduced physically-inconsistent synthetic rows. D's
   higher uncertainty (already established in this project: GPR CV R^2
   ~0.665-0.713 for D vs ~0.977-0.994 for Lc/Le) is instead communicated by
   propagating Lc's and Le's own predictive std under an explicit
   independence assumption: D_gp_std = sqrt(Lc_gp_std^2 + Le_gp_std^2).
   This is a conservative (likely-overstated) proxy, stated as such: Lc and
   Le are highly collinear in the real data (r=0.992), so their true joint
   noise is almost certainly positively correlated, which would make the
   real uncertainty in Lc-Le SMALLER than this independence-assumption
   estimate, not larger -- i.e. this proxy is deliberately not
   overconfident, at the cost of possibly overstating D's noise.
5. Near-duplicate filtering: any generated row whose (T1..T5) is within a
   small Euclidean tolerance of ANY original row (train+val+test) is
   dropped and re-sampled, so synthetic rows are not near-copies of real
   design points.
6. Plausibility bounds: generated Lc/Le/D more than 3x the training span
   beyond the observed original_train range are dropped and re-sampled
   (extrapolation guard -- consistent with FastSurrogate's own
   out-of-range warning logic, just enforced at generation time instead of
   left to the caller).

Every synthetic row carries provenance columns (`source`, per-target
`*_gp_std`) so synthetic data can never be silently confused with
original/experimental/CrysMAS data downstream.

Run: python3 synthetic/04_generate_synthetic_data.py [N_SAMPLES]
Output: synthetic/synthetic_crystal_growth_dataset.csv
"""
from __future__ import annotations

import sys
from pathlib import Path

import numpy as np
import pandas as pd
from sklearn.gaussian_process import GaussianProcessRegressor
from sklearn.gaussian_process.kernels import RBF, ConstantKernel, WhiteKernel
from sklearn.pipeline import Pipeline
from sklearn.preprocessing import StandardScaler

SEED = 42
N_SAMPLES_DEFAULT = 2000  # justified in the methodology doc / assumptions doc: n=96 original
                          # -> a modest multiple (~20x), not 1000-5000 at the high end, because
                          # a small-n GP interpolant does not become more informative just
                          # because more synthetic rows are drawn from it (see limitations doc).
INPUT_COLS = ["T1 (K)", "T2 (K)", "T3 (K)", "T4 (K)", "T5 (K)"]
DATA_DIR = Path(__file__).resolve().parent / "data"
OUT_PATH = Path(__file__).resolve().parent / "synthetic_crystal_growth_dataset.csv"


def gpr_kernel():
    """Identical kernel family to src/models.py::gpr_kernel (project consistency)."""
    return (
        ConstantKernel(1.0, (1e-3, 1e3))
        * RBF(length_scale=1.0, length_scale_bounds=(1e-2, 1e3))
        + WhiteKernel(noise_level=1e-3, noise_level_bounds=(1e-8, 1e0))
    )


def make_gpr_pipeline(seed: int) -> Pipeline:
    return Pipeline([
        ("scaler", StandardScaler()),
        ("model", GaussianProcessRegressor(
            kernel=gpr_kernel(), random_state=seed, normalize_y=True, n_restarts_optimizer=5
        )),
    ])


def sample_valid_inputs(rng: np.random.Generator, ranges: dict, n: int) -> np.ndarray:
    """Rejection-sample T1..T5 uniformly within `ranges` until
    T1>=T2>=T3>=T4>=T5 holds, matching 100% of the original data's
    ordering constraint (see 01_dataset_analysis.py)."""
    out = []
    max_tries = n * 200
    tries = 0
    while len(out) < n and tries < max_tries:
        batch = rng.uniform(
            low=[ranges[c][0] for c in INPUT_COLS],
            high=[ranges[c][1] for c in INPUT_COLS],
            size=(n * 4, 5),
        )
        tries += n * 4
        ok = (batch[:, 0] >= batch[:, 1]) & (batch[:, 1] >= batch[:, 2]) & \
             (batch[:, 2] >= batch[:, 3]) & (batch[:, 3] >= batch[:, 4])
        out.extend(batch[ok].tolist())
    if len(out) < n:
        raise RuntimeError(f"Rejection sampling only produced {len(out)}/{n} valid rows "
                            f"after {tries} tries -- the ordering constraint is very "
                            f"restrictive relative to the sampled ranges.")
    return np.array(out[:n])


def near_duplicate_mask(candidates: np.ndarray, reference: np.ndarray, tol: float) -> np.ndarray:
    """True where a candidate row's T1..T5 (scaled by column std) is within
    `tol` Euclidean distance of ANY reference (original) row."""
    ref_std = reference.std(axis=0)
    ref_std[ref_std == 0] = 1.0
    cand_s = candidates / ref_std
    ref_s = reference / ref_std
    is_dup = np.zeros(len(candidates), dtype=bool)
    for i in range(len(candidates)):
        d = np.sqrt(((ref_s - cand_s[i]) ** 2).sum(axis=1)).min()
        is_dup[i] = d < tol
    return is_dup


def main():
    n_samples = int(sys.argv[1]) if len(sys.argv) > 1 else N_SAMPLES_DEFAULT
    rng = np.random.default_rng(SEED)

    train = pd.read_csv(DATA_DIR / "original_train.csv")
    all_original = pd.concat([
        pd.read_csv(DATA_DIR / "original_train.csv"),
        pd.read_csv(DATA_DIR / "original_val.csv"),
        pd.read_csv(DATA_DIR / "original_test.csv"),
    ], ignore_index=True)  # used ONLY for near-duplicate checking (T1..T5 values are public
                            # design-space info, not leaked target information); the GENERATOR
                            # itself is fit exclusively on `train` above.

    X_train = train[INPUT_COLS]
    y_train = train[["Lc (m)", "Le (m)"]]  # D, P are derived algebraically below, never
                                             # generated by an independent model (see module
                                             # docstring: this preserves the exact D=Lc-Le
                                             # identity instead of breaking it).

    print(f"Fitting GPR generator on original_train.csv only (n={len(train)}) ...")
    gprs = {}
    train_r2 = {}
    for target in ["Lc (m)", "Le (m)"]:
        pipe = make_gpr_pipeline(SEED)
        pipe.fit(X_train, y_train[target])
        gprs[target] = pipe
        train_r2[target] = pipe.score(X_train, y_train[target])
    print("In-sample (train) R^2 per target (NOT a generalization estimate; see "
          "06_ml_evaluation.py for held-out numbers):")
    for t, r2 in train_r2.items():
        print(f"  {t}: {r2:.4f}")

    input_ranges = {c: (float(X_train[c].min()), float(X_train[c].max())) for c in INPUT_COLS}
    target_ranges = {c: (float(y_train[c].min()), float(y_train[c].max())) for c in y_train.columns}
    target_ranges["D (m)"] = (float(train["D (m)"].min()), float(train["D (m)"].max()))

    accepted_rows = []
    batch_target = max(200, n_samples // 4)
    dup_tol = 0.05  # Euclidean distance in std-normalized T1..T5 space
    n_dropped_dup = 0
    n_dropped_implausible = 0

    while len(accepted_rows) < n_samples:
        need = n_samples - len(accepted_rows)
        batch_n = max(need, batch_target)
        X_cand = sample_valid_inputs(rng, input_ranges, batch_n)
        X_cand_df = pd.DataFrame(X_cand, columns=INPUT_COLS)

        dup_mask = near_duplicate_mask(X_cand, all_original[INPUT_COLS].values, dup_tol)
        n_dropped_dup += int(dup_mask.sum())
        X_cand_df = X_cand_df.loc[~dup_mask].reset_index(drop=True)
        if len(X_cand_df) == 0:
            continue

        preds = {}
        stds = {}
        for target, pipe in gprs.items():
            scaler = pipe.named_steps["scaler"]
            model = pipe.named_steps["model"]
            Xs = scaler.transform(X_cand_df[INPUT_COLS])
            mean, std = model.predict(Xs, return_std=True)
            noise = rng.normal(loc=0.0, scale=std)  # noise = the GP's OWN predictive std,
                                                      # not an arbitrary noise model
            preds[target] = mean + noise
            stds[target] = std

        cand_out = X_cand_df.copy()
        cand_out["Lc (m)"] = preds["Lc (m)"]
        cand_out["Le (m)"] = preds["Le (m)"]
        cand_out["D (m)"] = cand_out["Lc (m)"] - cand_out["Le (m)"]  # exact identity, always
        cand_out["Lc_gp_std"] = stds["Lc (m)"]
        cand_out["Le_gp_std"] = stds["Le (m)"]
        # Propagated uncertainty under an independence assumption (conservative /
        # likely-overstated -- see module docstring for why this direction is the
        # honest one to err in, given Lc/Le's real r=0.992 collinearity).
        cand_out["D_gp_std"] = np.sqrt(stds["Lc (m)"] ** 2 + stds["Le (m)"] ** 2)

        # Plausibility guard: reject predictions far outside the observed
        # original_train output range (extrapolation guard, mirrors
        # FastSurrogate._validate_output's 0.5x-span rule, tightened to 1x
        # span here since generation should stay closer to the observed
        # regime than a one-off prediction call would need to).
        keep = np.ones(len(cand_out), dtype=bool)
        for col in ["Lc (m)", "Le (m)", "D (m)"]:
            lo, hi = target_ranges[col]
            span = hi - lo
            out_of_bounds = (cand_out[col] < lo - span) | (cand_out[col] > hi + span)
            keep &= ~out_of_bounds
        n_dropped_implausible += int((~keep).sum())
        cand_out = cand_out.loc[keep].reset_index(drop=True)

        accepted_rows.append(cand_out)
        if sum(len(c) for c in accepted_rows) >= n_samples:
            break

    synth = pd.concat(accepted_rows, ignore_index=True).iloc[:n_samples].copy()
    synth["P (m)"] = (synth["Lc (m)"] + synth["Le (m)"]) / 2.0  # algebraic, never generated independently
    synth["source"] = "synthetic_gpr_generated"
    synth["generator_train_n"] = len(train)
    synth["random_seed"] = SEED

    col_order = INPUT_COLS + ["Lc (m)", "Le (m)", "P (m)", "D (m)",
                               "Lc_gp_std", "Le_gp_std", "D_gp_std",
                               "source", "generator_train_n", "random_seed"]
    synth = synth[col_order]
    synth.to_csv(OUT_PATH, index=False)

    print(f"\nGenerated {len(synth)} synthetic rows -> {OUT_PATH}")
    print(f"Dropped as near-duplicate of an original row: {n_dropped_dup}")
    print(f"Dropped as implausible (>1x training span outside observed range): {n_dropped_implausible}")
    print(f"Mean D_gp_std / mean Lc_gp_std ratio (higher = D noisier, as expected, since D "
          f"propagates BOTH Lc's and Le's uncertainty): "
          f"{(synth['D_gp_std'].mean() / synth['Lc_gp_std'].mean()):.3f}")
    identity_gap = (synth["D (m)"] - (synth["Lc (m)"] - synth["Le (m)"])).abs().max()
    print(f"D = Lc - Le identity check on generated data (should be ~0): max abs gap = {identity_gap:.2e}")
    print("\nEvery row labeled source='synthetic_gpr_generated'. This is a statistical "
          "interpolant of the 96-row CrysMAS simulation sample, NOT new CrysMAS output "
          "and NOT experimental data. See synthetic/02_METHODOLOGY_SELECTION.md and "
          "synthetic/07_ASSUMPTIONS_AND_LIMITATIONS.md.")


if __name__ == "__main__":
    main()
